//! Format embedded translations without global mutable state or runtime file access.

use fluent_bundle::{FluentBundle, FluentResource};
use unic_langid::{LanguageIdentifier, langid};

pub(crate) use fluent_bundle::FluentArgs;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Language {
    English,
    Russian,
    Spanish,
}

impl Language {
    /// BCP 47 primary code passed to external modules.
    pub(crate) fn code(self) -> &'static str {
        match self {
            Self::English => "en",
            Self::Russian => "ru",
            Self::Spanish => "es",
        }
    }

    pub(crate) fn select(locale: Option<&str>) -> Self {
        let locale = locale.unwrap_or("en");
        let primary = locale.trim().split(['-', '_', '.', '@']).next();

        match primary.map(str::to_ascii_lowercase).as_deref() {
            Some("ru") => Self::Russian,
            Some("es") => Self::Spanish,
            _ => Self::English,
        }
    }

    fn identifier(self) -> LanguageIdentifier {
        match self {
            Self::English => langid!("en"),
            Self::Russian => langid!("ru"),
            Self::Spanish => langid!("es"),
        }
    }

    fn source(self) -> &'static str {
        match self {
            Self::English => include_str!("../../locales/en.ftl"),
            Self::Russian => include_str!("../../locales/ru.ftl"),
            Self::Spanish => include_str!("../../locales/es.ftl"),
        }
    }

    fn sources(self) -> [&'static str; 5] {
        let terminal = match self {
            Self::English => include_str!("../modules/terminal/locales/en.ftl"),
            Self::Russian => include_str!("../modules/terminal/locales/ru.ftl"),
            Self::Spanish => include_str!("../modules/terminal/locales/es.ftl"),
        };
        let deployment = match self {
            Self::English => include_str!("../modules/deployment/locales/en.ftl"),
            Self::Russian => include_str!("../modules/deployment/locales/ru.ftl"),
            Self::Spanish => include_str!("../modules/deployment/locales/es.ftl"),
        };
        let git = match self {
            Self::English => include_str!("../modules/git/locales/en.ftl"),
            Self::Russian => include_str!("../modules/git/locales/ru.ftl"),
            Self::Spanish => include_str!("../modules/git/locales/es.ftl"),
        };
        let pipelines = match self {
            Self::English => include_str!("../modules/pipelines/locales/en.ftl"),
            Self::Russian => include_str!("../modules/pipelines/locales/ru.ftl"),
            Self::Spanish => include_str!("../modules/pipelines/locales/es.ftl"),
        };
        [self.source(), terminal, deployment, git, pipelines]
    }
}

macro_rules! message_keys {
    ($($(#[$attribute:meta])* $variant:ident => $id:literal),+ $(,)?) => {
        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        pub(crate) enum Key { $($(#[$attribute])* $variant),+ }

        impl Key {
            #[cfg(test)]
            const ALL: &'static [Self] = &[$($(#[$attribute])* Self::$variant),+];

            fn id(self) -> &'static str {
                match self { $($(#[$attribute])* Self::$variant => $id),+ }
            }
        }
    };
}

